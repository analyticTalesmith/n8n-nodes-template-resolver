import { resolveTemplate } from "../../core/src/resolve";
import { TemplateValue } from "../../core/src/types";

// Capture a thrown error as text so a failure is always a matcher failure.
function render(
  template: string,
  entries: [string, TemplateValue][]
): string {
  try {
    return resolveTemplate(template, new Map(entries), { strictMode: false });
  } catch (e) {
    return `THROWN: ${(e as Error).message}`;
  }
}

describe("table cell escaping", () => {
  it("tc-01: a pipe inside a static-row cell is escaped with a backslash and keeps the column count", () => {
    const out = render(
      "{{TABLE}}{{ROW}}${{a}}|${{b}}{{END_ROW}}{{END_TABLE}}",
      [
        ["a", "x|y"],
        ["b", "z"],
      ]
    );
    expect(out).toBe("| x\\|y | z |");
  });

  it("tc-01: every pipe in a cell is escaped, in a table with a header", () => {
    const out = render(
      "{{TABLE}}{{HEADER}}H1|H2{{END_HEADER}}{{ROW}}${{a}}|ok{{END_ROW}}{{END_TABLE}}",
      [["a", "p|q|r"]]
    );
    expect(out).toBe("| H1 | H2 |\n|:-----|:-----|\n| p\\|q\\|r | ok |");
  });

  it("tc-02: a newline inside a cell is flattened to a single space", () => {
    const out = render(
      "{{TABLE}}{{ROW}}${{a}}|${{b}}{{END_ROW}}{{END_TABLE}}",
      [
        ["a", "line1\nline2"],
        ["b", "z"],
      ]
    );
    expect(out).toBe("| line1 line2 | z |");
  });

  it("tc-02: a CRLF newline inside a cell becomes one space", () => {
    const out = render("{{TABLE}}{{ROW}}${{a}}|z{{END_ROW}}{{END_TABLE}}", [
      ["a", "one\r\ntwo"],
    ]);
    expect(out).toBe("| one two | z |");
  });

  it("tc-02: pipe and newline in the same cell are both handled", () => {
    const out = render("{{TABLE}}{{ROW}}${{a}}|z{{END_ROW}}{{END_TABLE}}", [
      ["a", "a|b\nc"],
    ]);
    expect(out).toBe("| a\\|b c | z |");
  });

  it("tc-03: cells in rows generated by FOR escape pipes and flatten newlines", () => {
    const out = render(
      "{{TABLE}}{{HEADER}}Name|Note{{END_HEADER}}{{FOR rows AS r}}{{ROW}}${{r.name}}|${{r.note}}{{END_ROW}}{{END_FOR}}{{END_TABLE}}",
      [
        [
          "rows",
          [
            { name: "a|b", note: "n1\nn2" },
            { name: "c", note: "d|e" },
          ],
        ],
      ]
    );
    expect(out).toBe(
      "| Name | Note |\n|:-----|:-----|\n| a\\|b | n1 n2 |\n| c | d\\|e |"
    );
  });

  it("tc-03: header cells escape pipes and flatten newlines", () => {
    const out = render(
      "{{TABLE}}{{HEADER}}${{h1}}|${{h2}}{{END_HEADER}}{{ROW}}1|2{{END_ROW}}{{END_TABLE}}",
      [
        ["h1", "A|B"],
        ["h2", "C\nD"],
      ]
    );
    expect(out).toBe("| A\\|B | C D |\n|:-----|:-----|\n| 1 | 2 |");
  });

  it("guard-plain: cells without pipes or newlines render unchanged", () => {
    const out = render(
      "{{TABLE}}{{HEADER}}Name|Age{{END_HEADER}}{{ROW}}${{n}}|${{a}}{{END_ROW}}{{END_TABLE}}",
      [
        ["n", "Alice"],
        ["a", "30"],
      ]
    );
    expect(out).toBe("| Name | Age |\n|:-----|:-----|\n| Alice | 30 |");
  });

  it("guard-outside-table: pipes and newlines outside a table are not escaped", () => {
    const out = render("${{a}}", [["a", "x|y\nz"]]);
    expect(out).toBe("x|y\nz");
  });
});
